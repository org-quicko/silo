import fs from "fs/promises";
import path from "path";
import { BuildPaths } from "./build-paths";

/**
 * Writes the entrypoint the compile actually uses: the real CLI, preceded by a
 * `with { type: "file" }` import of every file in the admin UI's `dist`.
 *
 * Those imports survive `--compile` as paths under Bun's virtual filesystem,
 * which is what makes an installed `silo` serve its UI from any working
 * directory. Bun content-hashes the embedded names, so the map from request
 * path to embedded path is generated here and handed to `UiAssets` before the
 * CLI starts — importing the server's `main.ts` instead would run the CLI on
 * import, before there was anything to hand it.
 */
export class EntryGenerator {
  static async write(): Promise<string> {
    const files = await EntryGenerator.walk(BuildPaths.UiDist);
    if (files.length === 0) {
      throw new Error(
        `${BuildPaths.UiDist} is empty or missing — build the admin UI, or drop --skip-ui`
      );
    }

    const imports: string[] = [];
    const entries: string[] = [];
    files.forEach((relative, index) => {
      const identifier = `asset${index}`;
      const specifier = JSON.stringify(`../${BuildPaths.UiDist}/${relative}`);
      imports.push(`import ${identifier} from ${specifier} with { type: "file" };`);
      entries.push(`  ${JSON.stringify(`/${relative}`)}: ${identifier},`);
    });

    const source = `// GENERATED by tools/build. Do not edit, do not commit.
import { UiAssets } from "../apps/server/src/http/ui-assets";
import { Cli } from "${BuildPaths.CliEntry.replace("./", "../")}";
${imports.join("\n")}

UiAssets.useEmbedded({
${entries.join("\n")}
});

Cli.run();
`;

    await fs.mkdir(BuildPaths.GeneratedDir, { recursive: true });
    const entry = path.join(BuildPaths.GeneratedDir, "entry.ts");
    await Bun.write(entry, source);
    console.log(`embedding ${files.length} UI files from ${BuildPaths.UiDist}/`);
    return `./${entry}`;
  }

  /** Every file under `dir`, as paths relative to it with `/` separators —
   *  they become both import specifiers and URL paths. */
  private static async walk(dir: string, prefix = ""): Promise<string[]> {
    let dirents;
    try {
      dirents = await fs.readdir(dir, { withFileTypes: true });
    } catch {
      return [];
    }

    const found: string[] = [];
    for (const dirent of dirents.sort((left, right) => left.name.localeCompare(right.name))) {
      const relative = prefix ? `${prefix}/${dirent.name}` : dirent.name;
      if (dirent.isDirectory()) {
        found.push(...(await EntryGenerator.walk(path.join(dir, dirent.name), relative)));
      } else {
        found.push(relative);
      }
    }
    return found;
  }
}
